import {readFile, writeFile} from 'node:fs/promises';
// Copies the default charset, text palette and glyph modes of specs/video.json, and the
// console control codes of specs/kernel-abi.json, into the language server, so string
// previews draw the glyphs and colors MIA starts with.
const read = async name => JSON.parse(await readFile(new URL(`../specs/${name}`, import.meta.url), 'utf8'));
const video = await read('video.json'), abi = await read('kernel-abi.json');
const charset = video.chr.default, palette = video.palettes.default, modes = charset.glyphModes;
const output = '// Generated by scripts/generate-basic-charset.mjs from specs/video.json and specs/kernel-abi.json. Do not edit.\n\n'
  + `/** The ${charset.name} charset: bank 0 plane 0, 8 bytes per tile as hex, top row first; bit 0 of a row is its leftmost pixel. */\n`
  + 'export const clasciiGlyphs: readonly string[] = ' + JSON.stringify(charset.glyphs, null, 2) + ';\n\n'
  + `/** The ${palette.name} palette: 16 banks of 8 RGB565 colors. Color 0 is the backdrop blue and color 1 the bank's text ink. */\n`
  + 'export const defaultPaletteColors: readonly (readonly number[])[] = ' + JSON.stringify(palette.colors) + ';\n\n'
  + '/** Names of each bank\'s ink, the 16 text colors ESC 0-F and COLOR pick. */\n'
  + 'export const defaultInkNames: readonly string[] = ' + JSON.stringify(palette.inks) + ';\n\n'
  + '/** Screen-editor glyph modes: in mode m a key from firstKey to lastKey types tile (key + m * step) mod 256. */\n'
  + 'export const glyphModes = ' + JSON.stringify({count: modes.count, step: modes.step, firstKey: modes.firstKey, lastKey: modes.lastKey}) + ' as const;\n\n'
  + '/** Codes KERN_CHROUT acts on instead of drawing their tiles. */\n'
  + 'export const consoleControlCodes: readonly {code: number; symbol: string; action: string}[] = ' + JSON.stringify(abi.consoleControlCodes, null, 2) + ';\n';
const target = new URL('../packages/basic-lsp/src/charset-data.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output) throw Error('Generated BASIC charset data is stale; run npm run generate:basic-charset');
} else await writeFile(target, output);
