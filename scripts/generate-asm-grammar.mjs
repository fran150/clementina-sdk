import {readFile, writeFile} from 'node:fs/promises';
// Writes the VS Code TextMate grammar for Clementina assembly (ca65 syntax for the
// W65C02S, specs/machine.json). Beyond the generic 65C02/ca65 rules it names the
// symbols the SDK's public includes define, so the editor highlights exactly what
// a program can rely on: the asset runtime macros and routines from runtime.inc,
// and the constants that generate-includes.mjs writes from specs/*.json into
// clementina.inc and mia.inc. Internal names (rt__*, *_INC include guards and
// rt_internal.inc) are left out.
const asmDir = new URL('../packages/runtime/asm/', import.meta.url);
const read = name => readFile(new URL(name, asmDir), 'utf8');
const [runtime, clementina, mia] = await Promise.all([read('runtime.inc'), read('clementina.inc'), read('mia.inc')]);

const isPublic = name => !name.startsWith('rt__') && !/_INC$/u.test(name);
const unique = names => [...new Set(names)].filter(isPublic).sort();
const matchAll = (text, regex) => [...text.matchAll(regex)].map(match => match[1]);
const listed = (text, directive) => matchAll(text, new RegExp(`^\\s*\\.${directive}\\s+([^;\\n]+)`, 'gimu'))
  .flatMap(list => list.split(',').map(name => name.trim()).filter(Boolean));

const macros = unique(matchAll(runtime, /^\s*\.macro\s+([A-Za-z_][A-Za-z0-9_]*)/gimu));
const routines = unique(listed(runtime, 'global'));
const zeroPage = unique(listed(runtime, 'globalzp'));
const constants = unique([runtime, clementina, mia].flatMap(text => [
  ...matchAll(text, /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=/gmu),
  ...matchAll(text, /^\s*\.define\s+([A-Za-z_][A-Za-z0-9_]*)/gimu),
]));
if (!macros.length || !routines.length || !constants.length) throw Error('No runtime symbols found in packages/runtime/asm');

const words = names => `(?<![\\w@.])(?:${names.join('|')})(?![\\w@])`;
const bitOps = ['bbr', 'bbs', 'rmb', 'smb'].map(op => `${op}[0-7]`);
const mnemonics = ['adc', 'and', 'asl', 'bcc', 'bcs', 'beq', 'bit', 'bmi', 'bne', 'bpl', 'bra', 'brk', 'bvc', 'bvs',
  'clc', 'cld', 'cli', 'clv', 'cmp', 'cpx', 'cpy', 'dec', 'dex', 'dey', 'eor', 'inc', 'inx', 'iny', 'jmp', 'jsr',
  'lda', 'ldx', 'ldy', 'lsr', 'nop', 'ora', 'pha', 'php', 'phx', 'phy', 'pla', 'plp', 'plx', 'ply', 'rol', 'ror',
  'rti', 'rts', 'sbc', 'sec', 'sed', 'sei', 'sta', 'stp', 'stx', 'sty', 'stz', 'tax', 'tay', 'trb', 'tsb', 'tsx',
  'txa', 'txs', 'tya', 'wai', ...bitOps];
const id = '[A-Za-z_][A-Za-z0-9_]*';

const grammar = {
  $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
  name: 'Clementina Assembly',
  scopeName: 'source.clementina-asm',
  comment: 'Generated by scripts/generate-asm-grammar.mjs from packages/runtime/asm/*.inc. Do not edit.',
  patterns: [
    {include: '#comment'},
    {include: '#string'},
    {include: '#label-definition'},
    {include: '#definition'},
    {include: '#directive'},
    {include: '#instruction'},
    {include: '#clementina'},
    {include: '#number'},
    {include: '#label-reference'},
    {include: '#operator'},
  ],
  repository: {
    comment: {name: 'comment.line.semicolon.clementina-asm', match: ';.*$'},
    string: {patterns: [
      {name: 'string.quoted.double.clementina-asm', begin: '"', end: '"|$', patterns: [{name: 'constant.character.escape.clementina-asm', match: '\\\\.'}]},
      {name: 'string.quoted.single.clementina-asm', match: "'(?:\\\\.|[^'\\\\])'"},
    ]},
    'label-definition': {patterns: [
      {match: `^\\s*(@?${id})(:{1,2})`, captures: {1: {name: 'entity.name.label.clementina-asm'}, 2: {name: 'punctuation.separator.label.clementina-asm'}}},
      {match: '^\\s*(:)(?=\\s|;|$)', captures: {1: {name: 'entity.name.label.unnamed.clementina-asm'}}},
    ]},
    definition: {patterns: [
      {match: `(?i)(\\.(?:macro|mac))\\s+(${id})`, captures: {1: {name: 'keyword.control.directive.clementina-asm'}, 2: {name: 'entity.name.function.macro.clementina-asm'}}},
      {match: `(?i)(\\.proc)\\s+(${id})`, captures: {1: {name: 'keyword.control.directive.clementina-asm'}, 2: {name: 'entity.name.function.clementina-asm'}}},
      {match: `(?i)(\\.(?:scope|struct|union|enum))\\s+(${id})`, captures: {1: {name: 'keyword.control.directive.clementina-asm'}, 2: {name: 'entity.name.type.clementina-asm'}}},
      {match: `(?i)(\\.define)\\s+(${id})`, captures: {1: {name: 'keyword.control.directive.clementina-asm'}, 2: {name: 'entity.name.constant.clementina-asm'}}},
      {match: `^\\s*(${id})\\s*(:?=)`, captures: {1: {name: 'entity.name.constant.clementina-asm'}, 2: {name: 'keyword.operator.assignment.clementina-asm'}}},
    ]},
    directive: {name: 'keyword.control.directive.clementina-asm', match: `(?<![\\w@])\\.${id}`},
    instruction: {patterns: [
      {match: '(?i)(?<![\\w@.])(asl|lsr|rol|ror|inc|dec)\\s+(a)(?=\\s*(?:;|$))', captures: {1: {name: 'keyword.mnemonic.clementina-asm'}, 2: {name: 'variable.language.register.clementina-asm'}}},
      {name: 'keyword.mnemonic.clementina-asm', match: `(?i)(?<![\\w@.])(?:${mnemonics.join('|')})(?![\\w@])`},
      {match: '(?i),\\s*([xy])(?![\\w@])', captures: {1: {name: 'variable.language.register.clementina-asm'}}},
    ]},
    clementina: {patterns: [
      {name: 'support.function.macro.clementina-asm', match: words(macros)},
      {name: 'support.function.routine.clementina-asm', match: words(routines)},
      {name: 'support.variable.zeropage.clementina-asm', match: words(zeroPage)},
      {name: 'support.constant.clementina-asm', match: words(constants)},
    ]},
    number: {patterns: [
      {name: 'constant.numeric.hex.clementina-asm', match: '\\$[0-9A-Fa-f]+(?![\\w])'},
      {name: 'constant.numeric.hex.clementina-asm', match: '(?<![\\w@])[0-9][0-9A-Fa-f]*[hH](?![\\w])'},
      {name: 'constant.numeric.binary.clementina-asm', match: '(?<![\\w)])%[01]+(?![\\w])'},
      {name: 'constant.numeric.decimal.clementina-asm', match: '(?<![\\w@$])[0-9]+(?![\\w])'},
    ]},
    'label-reference': {patterns: [
      {name: 'entity.name.label.unnamed.clementina-asm', match: ':(?:\\++|-+|<+|>+)'},
      {name: 'variable.other.label.local.clementina-asm', match: `@${id}`},
    ]},
    operator: {patterns: [
      {name: 'keyword.operator.immediate.clementina-asm', match: '#'},
      {name: 'keyword.operator.clementina-asm', match: '<<|>>|<=|>=|<>|&&|\\|\\||[-+*/&|^~!<>=]'},
    ]},
  },
};

const output = JSON.stringify(grammar, null, 2) + '\n';
const target = new URL('../packages/vscode-extension/syntaxes/clementina-asm.tmLanguage.json', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output) throw Error('Generated assembly grammar is stale; run npm run generate:asm-grammar');
} else await writeFile(target, output);
