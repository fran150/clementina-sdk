import {readFile, readdir, writeFile} from 'node:fs/promises';
import {join, relative, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
// Embeds the project templates so `clementina new` needs no SDK files on disk,
// which lets the CLI ship as a single standalone executable.
const root = fileURLToPath(new URL('../templates/', import.meta.url));
const sources = {basic: 'basic-game', assembly: 'asm-game'};

async function files(directory) {
  const entries = await readdir(directory, {withFileTypes: true});
  const nested = await Promise.all(entries.map(entry => entry.isDirectory() ? files(join(directory, entry.name)) : [join(directory, entry.name)]));
  return nested.flat();
}

const templates = {};
for (const [name, directory] of Object.entries(sources)) {
  const base = join(root, directory);
  const paths = (await files(base)).map(path => relative(base, path).split(sep).join('/')).sort();
  templates[name] = {};
  for (const path of paths) templates[name][path] = await readFile(join(base, path), 'utf8');
}
const output = '// Generated by scripts/generate-templates.mjs from templates/. Do not edit.\n'
  + '/** Every file of each `clementina new` template, keyed by template name and project-relative path. */\n'
  + 'export const templateFiles: Readonly<Record<string, Readonly<Record<string, string>>>> = ' + JSON.stringify(templates, null, 2) + ';\n';
const target = new URL('../packages/cli/src/templates.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output) throw Error('Generated templates are stale; run npm run generate:templates');
} else await writeFile(target, output);
