import {readFile, readdir, writeFile} from 'node:fs/promises';
import {join, relative, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
// Embeds the project starter so `clementina new` needs no SDK files on disk,
// which lets the CLI ship as a single standalone executable.
const base = fileURLToPath(new URL('../templates/starter/', import.meta.url));

async function files(directory) {
  const entries = await readdir(directory, {withFileTypes: true});
  const nested = await Promise.all(entries.map(entry => entry.isDirectory() ? files(join(directory, entry.name)) : [join(directory, entry.name)]));
  return nested.flat();
}

const starter = {};
const paths = (await files(base)).map(path => relative(base, path).split(sep).join('/')).sort();
for (const path of paths) starter[path] = await readFile(join(base, path), 'utf8');
const output = '// Generated by scripts/generate-templates.mjs from templates/starter/. Do not edit.\n'
  + '/** Every file of the `clementina new` starter, keyed by project-relative path. */\n'
  + 'export const starterFiles: Readonly<Record<string, string>> = ' + JSON.stringify(starter, null, 2) + ';\n';
const target = new URL('../packages/cli/src/templates.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output) throw Error('Generated templates are stale; run npm run generate:templates');
} else await writeFile(target, output);
