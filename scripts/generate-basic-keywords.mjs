import {readFile, writeFile} from 'node:fs/promises';
// Copies the keyword entries of specs/basic.json into the language server, so the
// editor shows the same syntax, argument ranges and summaries the spec records.
const spec = JSON.parse(await readFile(new URL('../specs/basic.json', import.meta.url), 'utf8'));
const output = '// Generated by scripts/generate-basic-keywords.mjs from specs/basic.json. Do not edit.\n'
  + "import type {BasicKeywordEntry} from './types.js';\n\n"
  + '/** Syntax, arguments, ranges, and summaries for every ROM keyword, in token-table order. */\n'
  + 'export const basicKeywordEntries: readonly BasicKeywordEntry[] = ' + JSON.stringify(spec.keywords.entries, null, 2) + ';\n';
const target = new URL('../packages/basic-lsp/src/keyword-data.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output) throw Error('Generated BASIC keyword data is stale; run npm run generate:basic-keywords');
} else await writeFile(target, output);
