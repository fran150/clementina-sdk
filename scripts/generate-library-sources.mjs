import {readFile, readdir, writeFile} from 'node:fs/promises';
// Embeds the Clementina library's ca65 sources so the builder needs no package files on disk,
// which lets the CLI ship as a single standalone executable.
const directory = new URL('../packages/lib/asm/', import.meta.url);
const names = (await readdir(directory)).filter(name => /\.(?:s|inc)$/u.test(name)).sort();
const files = {};
for (const name of names) files[name] = await readFile(new URL(name, directory), 'utf8');
const output = '// Generated by scripts/generate-library-sources.mjs from asm/. Do not edit.\n'
  + '/** Contents of every Clementina library ca65 source and include, keyed by file name. */\n'
  + 'export const libraryFiles: Readonly<Record<string, string>> = ' + JSON.stringify(files, null, 2) + ';\n';
const target = new URL('../packages/lib/src/sources.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output) throw Error('Generated library sources are stale; run npm run generate:library');
} else await writeFile(target, output);
