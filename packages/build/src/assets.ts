// The asset build: the files the game loads from the card, the descriptors
// and constants the game assembles with, and the memory report. Pure: the
// caller writes the files. docs/gamedev/builder.md describes every format.
import {
  encodeBackgroundFile, encodeOverlayFile, encodePaletteConfig, encodeSongFile, encodeSoundFile, encodeSpriteFile, encodeTileset,
  type AnimationAsset, type ShapeAsset,
} from '@clementina/assets';
import {diagnostic, result, type ClementinaDiagnostic, type ValidationResult} from '@clementina/core';
import {BUILTIN_SLOTS, type PortableProject, type ProjectAssetBuildKind, type ProjectAssetInclude} from '@clementina/project';
import {bankLocation} from '@clementina/runtime';

export interface PlannedSlot {
  name: string;
  builtin: boolean;
  space: 'mia' | 'bank';
  /** The runtime location of its first byte. */
  location: number;
  size: number;
  mia?: number;
  bank?: number;
  address?: number;
}

export interface PlannedItem {kind: 'shape' | 'animation'; id: string; name: string; label: string; number: number; offset: number; size: number}
export interface PlannedPlaceholder {id: string; name: string; label: string; number: number; col: number; row: number; width: number; height: number}

export interface PlannedAsset {
  kind: ProjectAssetBuildKind;
  id: string;
  name: string;
  /** The descriptor's label in assets.s. */
  label: string;
  /** The file's name, and its path on the card relative to the game's folder. */
  file: string;
  path: string;
  slot: string;
  bytes: Uint8Array;
  /** Sprite files: shapes, then animations. */
  items?: PlannedItem[];
  placeholders?: PlannedPlaceholder[];
  width?: number;
  height?: number;
  voiceOffsets?: Array<number | null>;
  entries?: number;
  bpp?: 1 | 3;
}

export interface MemoryReport {
  format: 'clementina-memory-report';
  version: 1;
  folder: string;
  slots: Array<Omit<PlannedSlot, 'location'> & {location: number; used: number; assets: Array<{kind: ProjectAssetBuildKind; id: string; name: string; label: string; file: string; size: number}>}>;
  diagnostics: ClementinaDiagnostic[];
  /** Assembled CODE bytes per runtime module, populated by buildProject. */
  runtimeCode?: Record<string, number>;
}

export interface AssetBuildPlan {
  folder: string;
  checks: boolean;
  slots: PlannedSlot[];
  assets: PlannedAsset[];
  assetsInc: string;
  assetsS: string;
  report: MemoryReport;
}

const PREFIX: Record<ProjectAssetBuildKind, string> = {paletteConfig: 'PAL', tileset: 'CHR', background: 'BG', overlay: 'OVL', sprites: 'SPR', song: 'SONG', sound: 'SFX'};
const EXTENSION: Record<ProjectAssetBuildKind, string> = {paletteConfig: 'PAL', tileset: 'CHR', background: 'BG', overlay: 'OVL', sprites: 'SPR', song: 'SNG', sound: 'SFX'};
const TYPE_NAME: Record<ProjectAssetBuildKind, string> = {paletteConfig: 'RT_PALETTES', tileset: 'RT_TILESET', background: 'RT_BACKGROUND', overlay: 'RT_OVERLAY', sprites: 'RT_SPRITES', song: 'RT_SONG', sound: 'RT_SOUND'};
/** The kind each built-in slot is for. */
const BUILTIN_KIND: Record<string, ProjectAssetBuildKind> = {palettes: 'paletteConfig', overlay: 'overlay', ...Object.fromEntries(Array.from({length: 8}, (_, i) => [`chr${i}`, 'tileset']))};

const HEADER = '; Generated by the Clementina SDK from clementina.yaml. Do not edit.';
const hex = (n: number, digits = 6) => `$${n.toString(16).toUpperCase().padStart(digits, '0')}`;
/** An assembler identifier made of a name: upper case, anything else an underscore. */
export const identifier = (name: string): string => name.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'ASSET';

/** Plans the asset build of a validated project; carry on only when ok. */
export function planAssetBuild(project: PortableProject): ValidationResult<AssetBuildPlan> {
  const config = project.manifest.build?.assets;
  if (!config) return result(undefined, [diagnostic('build.assets', '/build/assets', 'The project has no asset build')]);
  const {assets} = project;
  const diagnostics: ClementinaDiagnostic[] = [];
  const warn = (code: string, path: string, message: string) => diagnostics.push({...diagnostic(code, path, message), severity: 'warning'});
  const folder = config.folder ?? 'ASSETS';

  const slots: PlannedSlot[] = [
    ...BUILTIN_SLOTS.map(s => ({name: s.name, builtin: true, space: 'mia' as const, location: s.mia, size: s.size, mia: s.mia})),
    ...config.slots.map(s => s.mia !== undefined
      ? {name: s.name, builtin: false, space: 'mia' as const, location: s.mia, size: s.size, mia: s.mia}
      : {name: s.name, builtin: false, space: 'bank' as const, location: bankLocation(s.bank!, s.address!), size: s.size, bank: s.bank, address: s.address}),
  ];
  const slotByName = new Map(slots.map(s => [s.name, s]));

  const labels = new Set<string>(), files = new Set<string>();
  const unique = (base: string) => { let label = base; for (let n = 2; labels.has(label); n++) label = `${base}_${n}`; labels.add(label); return label; };
  // Files named by the build fill in around those the manifest names.
  for (const entry of config.include) if (entry.file) files.add(entry.file.toUpperCase());
  const fileName = (entry: ProjectAssetInclude, name: string) => {
    if (entry.file) return entry.file;
    const stem = identifier(name).slice(0, 8), extension = EXTENSION[entry.kind];
    let file = `${stem}.${extension}`;
    for (let n = 1; files.has(file.toUpperCase()); n++) {
      const suffix = String(n).padStart(2, '0');
      file = `${stem.slice(0, 8 - suffix.length)}${suffix}.${extension}`;
    }
    files.add(file.toUpperCase());
    return file;
  };

  const planned: PlannedAsset[] = [];
  config.include.forEach((entry, index) => {
    const path = `/build/assets/include/${index}`;
    const slot = slotByName.get(entry.slot)!;
    const base = {kind: entry.kind, id: entry.id, slot: entry.slot};
    let asset: PlannedAsset;
    try {
      switch (entry.kind) {
        case 'paletteConfig': {
          const a = assets.paletteConfigs.find(x => x.id === entry.id)!;
          asset = {...base, name: a.name, label: '', file: '', path: '', bytes: encodePaletteConfig(a, assets.palettes)};
          break;
        }
        case 'tileset': {
          const a = assets.tilesets.find(x => x.id === entry.id)!;
          asset = {...base, name: a.name, label: '', file: '', path: '', bytes: encodeTileset(a), bpp: a.bpp};
          break;
        }
        case 'background': {
          const a = assets.backgrounds.find(x => x.id === entry.id)!;
          asset = {...base, name: a.name, label: '', file: '', path: '', bytes: encodeBackgroundFile(a), width: a.width, height: a.height};
          break;
        }
        case 'overlay': {
          const a = assets.overlays.find(x => x.id === entry.id)!;
          if (a.placeholders.length > 255) {
            diagnostics.push(diagnostic('build.assets.overlay.placeholders', path, `${a.name} has more than 255 placeholders`));
            return;
          }
          asset = {...base, name: a.name, label: '', file: '', path: '', bytes: encodeOverlayFile(a),
            placeholders: a.placeholders.map((p, number) => ({id: p.id, name: p.name, label: '', number, col: p.col, row: p.row, width: p.width, height: p.height}))};
          break;
        }
        case 'sprites': {
          const tileset = assets.tilesets.find(x => x.id === entry.id)!;
          const shapes: ShapeAsset[] = assets.shapes.filter(s => s.tilesetId === tileset.id);
          const inFile = new Set(shapes.map(s => s.id));
          const animations: AnimationAsset[] = assets.animations.filter(a => a.frames.length > 0 && inFile.has(a.frames[0].shapeId));
          if (shapes.length + animations.length > 255) {
            diagnostics.push(diagnostic('build.assets.sprites.items', path, `${tileset.name}'s sprite file has ${shapes.length + animations.length} shapes and animations; at most 255 fit`));
            return;
          }
          const file = encodeSpriteFile(shapes, animations);
          asset = {...base, name: tileset.name, label: '', file: '', path: '', bytes: file.bytes, items: [
            ...file.shapes.map((s, number) => ({kind: 'shape' as const, id: s.id, name: s.name, label: `SHAPE_${identifier(s.name)}`, number, offset: s.offset, size: s.size})),
            ...file.animations.map((a, number) => ({kind: 'animation' as const, id: a.id, name: a.name, label: `ANIM_${identifier(a.name)}`, number, offset: a.offset, size: a.size})),
          ]};
          break;
        }
        case 'song': {
          const a = assets.songs.find(x => x.id === entry.id)!;
          const file = encodeSongFile(a, assets.instruments);
          if (file.bytes.length === 0) {
            diagnostics.push(diagnostic('build.assets.song.empty', path, `${a.name} has no notes, so there is nothing to play`));
            return;
          }
          asset = {...base, name: a.name, label: '', file: '', path: '', bytes: file.bytes, voiceOffsets: file.voiceOffsets};
          break;
        }
        case 'sound': {
          const a = assets.sounds.find(x => x.id === entry.id)!;
          const file = encodeSoundFile(a);
          asset = {...base, name: a.name, label: '', file: '', path: '', bytes: file.bytes, entries: file.entries};
          break;
        }
      }
    } catch (error) {
      diagnostics.push(diagnostic('build.assets.encode', path, error instanceof Error ? error.message : String(error)));
      return;
    }
    asset.label = unique(`${PREFIX[entry.kind]}_${identifier(asset.name)}`);
    asset.file = fileName(entry, asset.name);
    asset.path = `${folder}/${asset.file}`;
    asset.placeholders?.forEach(p => { p.label = unique(`${asset.label}_${identifier(p.name)}`); });
    asset.items?.forEach(item => { item.label = unique(item.label); });

    const size = asset.bytes.length;
    if (size > slot.size) {
      const message = `${asset.name} (${size} bytes) is larger than slot ${slot.name} (${slot.size} bytes)`;
      if (entry.kind === 'background') warn('build.assets.slot.partial', `${path}/slot`, `${message}: only LoadRows, LoadColumns and LoadRect can use the slot`);
      else diagnostics.push(diagnostic('build.assets.slot.size', `${path}/slot`, message));
    }
    if (entry.kind === 'song' && slot.space === 'bank') warn('build.assets.song.bank', `${path}/slot`, `${asset.name} is in a bank: the sequencer reads MIA RAM, so copy it there (Relocate) before PlaySong`);
    if (slot.builtin && BUILTIN_KIND[slot.name] !== entry.kind) warn('build.assets.slot.builtin', `${path}/slot`, `${asset.name} loads into ${slot.name}, which holds ${BUILTIN_KIND[slot.name] === 'tileset' ? 'a CHR bank' : slot.name === 'palettes' ? 'the palettes' : 'the overlay'} on screen`);
    planned.push(asset);
  });

  const report: MemoryReport = {
    format: 'clementina-memory-report', version: 1, folder,
    slots: slots.map(slot => {
      const inSlot = planned.filter(a => a.slot === slot.name);
      return {...slot, used: Math.max(0, ...inSlot.map(a => a.bytes.length)),
        assets: inSlot.map(a => ({kind: a.kind, id: a.id, name: a.name, label: a.label, file: a.file, size: a.bytes.length}))};
    }),
    diagnostics,
  };
  const plan: AssetBuildPlan = {folder, checks: config.checks ?? true, slots, assets: planned, assetsInc: '', assetsS: '', report};
  plan.assetsInc = renderAssetsInc(plan);
  plan.assetsS = renderAssetsS(plan);
  return result(plan, diagnostics);
}

/** Constants and declarations: slots, assets, shapes and animations, placeholders. */
export function renderAssetsInc(plan: Pick<AssetBuildPlan, 'slots' | 'assets'>): string {
  const lines = [HEADER, '.ifndef ASSETS_INC', 'ASSETS_INC = 1', '.include "runtime.inc"', '',
    '; Slots: a location (a MIA address, or $80 | bank and a CPU address), and a size.'];
  for (const slot of plan.slots) {
    const name = `SLOT_${identifier(slot.name)}`;
    lines.push(`${name} = ${hex(slot.location)}`, `${name}_SIZE = ${slot.size}`);
  }
  if (plan.assets.length) {
    lines.push('', '; Assets. Their descriptors are in assets.s.', `.global ${plan.assets.map(a => a.label).join(', ')}`);
    for (const a of plan.assets) {
      lines.push(`${a.label}_SIZE = ${a.bytes.length}`);
      if (a.width !== undefined) lines.push(`${a.label}_WIDTH = ${a.width}`, `${a.label}_HEIGHT = ${a.height}`);
      if (a.voiceOffsets) lines.push(`${a.label}_VOICES = %${a.voiceOffsets.map(o => o === null ? '0' : '1').reverse().join('')}`);
      if (a.entries !== undefined) lines.push(`${a.label}_FRAMES = ${a.entries - 1}`);
    }
  }
  const items = plan.assets.flatMap(a => a.items ?? []);
  if (items.length) {
    lines.push('', '; Shapes and animations: their number in their sprite file, and where they are in it.');
    for (const item of items) lines.push(`${item.label} = ${item.number}`, `${item.label}_OFFSET = ${item.offset}`, `${item.label}_SIZE = ${item.size}`);
  }
  const holes = plan.assets.flatMap(a => a.placeholders ?? []);
  if (holes.length) {
    lines.push('', '; Overlay placeholders: their number, then column, row, width and height.');
    for (const p of holes) lines.push(`${p.label} = ${p.number}`, `${p.label}_COL = ${p.col}`, `${p.label}_ROW = ${p.row}`, `${p.label}_WIDTH = ${p.width}`, `${p.label}_HEIGHT = ${p.height}`);
  }
  lines.push('', '.endif', '');
  return lines.join('\n');
}

/** One descriptor per asset, and each sprite file's item and location tables. */
export function renderAssetsS(plan: Pick<AssetBuildPlan, 'slots' | 'assets'>): string {
  const slotByName = new Map(plan.slots.map(s => [s.name, s]));
  const data: string[] = [], rodata: string[] = [];
  for (const a of plan.assets) {
    const slot = slotByName.get(a.slot)!;
    data.push(`${a.label}:`, `        .byte ${TYPE_NAME[a.kind]}`, `        .faraddr RT_NOT_LOADED, ${hex(slot.location)}, ${a.bytes.length}`, `        .addr ${a.label}_PATH`);
    rodata.push(`${a.label}_PATH: .asciiz ${JSON.stringify(a.path)}`);
    switch (a.kind) {
      case 'tileset': data.push(`        .byte ${a.bpp === 1 ? 1 : 0}`); break;
      case 'background': data.push(`        .word ${a.width}, ${a.height}`, '        .word 0, 0, 0, 0              ; the window: nothing loaded'); break;
      case 'overlay': {
        const holes = a.placeholders!;
        data.push(`        .byte ${holes.length}`, `        .addr ${holes.length ? `${a.label}_HOLES` : 0}`);
        if (holes.length) rodata.push(`${a.label}_HOLES:`, ...holes.map(p => `        .byte ${p.col}, ${p.row}, ${p.width}, ${p.height}   ; ${p.name}`));
        break;
      }
      case 'sprites': {
        const items = a.items!;
        data.push(`        .byte ${items.filter(i => i.kind === 'shape').length}, ${items.filter(i => i.kind === 'animation').length}`, `        .addr ${a.label}_ITEMS, ${a.label}_LOCS`);
        rodata.push(`${a.label}_ITEMS:`, ...items.map(i => `        .faraddr ${i.offset}\n        .word ${i.size}                   ; ${i.kind} ${i.name}`));
        data.push(`${a.label}_LOCS:`, `        .repeat ${items.length}`, '        .faraddr RT_NOT_LOADED', '        .endrepeat');
        break;
      }
      case 'song': data.push(`        .word ${a.voiceOffsets!.map(o => o === null ? '$FFFF' : String(o)).join(', ')}`); break;
      case 'sound': data.push(`        .word ${a.entries}`); break;
      case 'paletteConfig': break;
    }
  }
  return [HEADER, '.setcpu "65C02"', '.include "assets.inc"', '', '.segment "DATA"', ...data, '', '.segment "RODATA"', ...rodata, ''].join('\n');
}
